// tools/geo_build.mjs: vendor base-map geometry for the map capabilities (src/presets/map.js) as plain scripts the page
// loads before drawing (file:// pages can't fetch JSON reliably). Source: Natural Earth via the world-atlas package
// (public-domain data, ISC package; devDependency). Coordinates rounded to 0.01° (~1 km): far below what a frame shows.
//   node tools/geo_build.mjs          → src/geo/land_50m.js (window.GEO.land50, a GeoJSON MultiPolygon)
//                                       src/geo/countries_50m.js (window.GEO.countries50: { name → geometry }, modern borders)
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';

const round = a => typeof a[0] === 'number' ? [Math.round(a[0] * 100) / 100, Math.round(a[1] * 100) / 100] : a.map(round);
for (const [res, key] of [['50m', 'land50']]) {
  const topo = JSON.parse(readFileSync(`node_modules/world-atlas/land-${res}.json`, 'utf8'));
  const geo = feature(topo, topo.objects.land), g = geo.features ? geo.features[0].geometry : geo.geometry;
  g.coordinates = round(g.coordinates);
  const src = `// GENERATED by tools/geo_build.mjs from Natural Earth ${res} land (world-atlas ${JSON.parse(readFileSync('node_modules/world-atlas/package.json', 'utf8')).version}; public domain). Do not edit.\n` +
    `(window.GEO = window.GEO || {}).${key} = { source: 'Natural Earth 1:${res} land (naturalearthdata.com), public domain', geometry: ${JSON.stringify(g)} };\n`;
  writeFileSync(`src/geo/land_${res}.js`, src);
  console.log(`src/geo/land_${res}.js  ${(src.length / 1024).toFixed(0)} KB`);
}

// countries (modern Natural Earth admin-0 borders, by English name) for mapRegion
{
  const topo = JSON.parse(readFileSync('node_modules/world-atlas/countries-50m.json', 'utf8')), fc = feature(topo, topo.objects.countries), out = {};
  for (const f of fc.features) if (f.geometry) { f.geometry.coordinates = round(f.geometry.coordinates); out[f.properties.name] = f.geometry; }
  const src = `// GENERATED by tools/geo_build.mjs from Natural Earth 1:50m admin-0 countries (world-atlas; public domain). MODERN borders. Do not edit.\n` +
    `(window.GEO = window.GEO || {}).countries50 = ${JSON.stringify(out)};\n`;
  writeFileSync('src/geo/countries_50m.js', src);
  console.log(`src/geo/countries_50m.js  ${(src.length / 1024).toFixed(0)} KB, ${Object.keys(out).length} countries`);
}

// first-level divisions (provinces / states) for mapRegion `units`, mapTransfer and mapHighlight: historical or
// partial territories are drawn as unions of modern provinces, and the manifest says which and why (sourced `data`).
//   node tools/geo_build.mjs --admin1=<ne_10m_admin_1_states_provinces.geojson> [--countries=THA,LAO,KHM,MYS,MMR,VNM | all] [--tolerance=.01]
// Source: Natural Earth 1:10m admin-1 (public domain; github.com/nvkelso/natural-earth-vector, geojson/). Keys are
// "<ISO3>/<name>" (e.g. "LAO/Champasak"). Simplified (Douglas-Peucker, 0.01°) and rounded to 0.01°.
const arg = k => process.argv.find(a => a.startsWith(`--${k}=`))?.split('=').slice(1).join('=');
const dpSimp = tol => {   // Douglas-Peucker for rings (closed rings: simplified as two halves) and polygons
  const dp = (pts, eps) => {
    if (pts.length < 4) return pts;
    const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1; const st = [[0, pts.length - 1]];
    while (st.length) { const [a, b] = st.pop(); let m = -1, md = eps;
      const [ax, ay] = pts[a], [bx, by] = pts[b], L = Math.hypot(bx - ax, by - ay) || 1e-12;
      for (let i = a + 1; i < b; i++) { const d = Math.abs((bx - ax) * (ay - pts[i][1]) - (ax - pts[i][0]) * (by - ay)) / L; if (d > md) { md = d; m = i; } }
      if (m > 0) { keep[m] = 1; st.push([a, m], [m, b]); } }
    return pts.filter((_, i) => keep[i]);
  };
  const ring = r => { const m = r.length >> 1, s = round([...dp(r.slice(0, m + 1), tol).slice(0, -1), ...dp(r.slice(m), tol)]); return s.length >= 4 ? s : null; };
  return g => g.type === 'Polygon' ? { type: 'Polygon', coordinates: g.coordinates.map(ring).filter(Boolean) }
    : { type: 'MultiPolygon', coordinates: g.coordinates.map(p => p.map(ring).filter(Boolean)).filter(p => p.length) };
};

// detailed country borders for close shots (map.js prefers them to countries50; same English names)
//   node tools/geo_build.mjs --countries10=<ne_10m_admin_0_countries.geojson> [--tolerance10=.008]
// Source: Natural Earth 1:10m admin-0 (public domain; github.com/nvkelso/natural-earth-vector, geojson/).
if (arg('countries10')) {
  const fc = JSON.parse(readFileSync(arg('countries10'), 'utf8')), tol = +(arg('tolerance10') || .008), simp = dpSimp(tol), out = {};
  const ALIAS = { 'North Macedonia': 'Macedonia' };   // the 1:50m set's older name, kept so manifests stay valid
  for (const f of fc.features) if (f.geometry) { const n = f.properties.NAME; out[n] = simp(f.geometry); if (ALIAS[n]) out[ALIAS[n]] = out[n]; }
  const src = `// GENERATED by tools/geo_build.mjs --countries10 from Natural Earth 1:10m admin-0 countries (public domain), tolerance ${tol}°. MODERN borders. Do not edit.\n` +
    `(window.GEO = window.GEO || {}).countries10 = ${JSON.stringify(out)};\n`;
  writeFileSync('src/geo/countries_10m.js', src);
  console.log(`src/geo/countries_10m.js  ${(src.length / 1024).toFixed(0)} KB, ${Object.keys(out).length} countries`);
}
// rivers (map.js mapBase rivers: true): every Natural Earth 1:10m river and lake centreline, simplified, by name
//   node tools/geo_build.mjs --rivers=<ne_10m_rivers_lake_centerlines.geojson> [--tolerance10=.008]
if (arg('rivers')) {
  const fc = JSON.parse(readFileSync(arg('rivers'), 'utf8')), tol = +(arg('tolerance10') || .008), lines = [];
  const dp = (pts, eps) => { if (pts.length < 3) return pts; const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1; const st = [[0, pts.length - 1]];
    while (st.length) { const [a, b] = st.pop(); let m = -1, md = eps; const [ax, ay] = pts[a], [bx, by] = pts[b], L = Math.hypot(bx - ax, by - ay) || 1e-12;
      for (let i = a + 1; i < b; i++) { const d = Math.abs((bx - ax) * (ay - pts[i][1]) - (ax - pts[i][0]) * (by - ay)) / L; if (d > md) { md = d; m = i; } }
      if (m > 0) { keep[m] = 1; st.push([a, m], [m, b]); } }
    return pts.filter((_, i) => keep[i]); };
  for (const f of fc.features) { if (!f.geometry) continue; const parts = f.geometry.type === 'LineString' ? [f.geometry.coordinates] : f.geometry.coordinates;
    const coords = parts.map(p => round(dp(p, tol))).filter(p => p.length > 1); if (coords.length) lines.push({ n: f.properties.name || '', r: f.properties.scalerank ?? 9, c: coords }); }
  const src = `// GENERATED by tools/geo_build.mjs --rivers from Natural Earth 1:10m rivers and lake centrelines (public domain), tolerance ${tol}°. Do not edit.\n` +
    `(window.GEO = window.GEO || {}).rivers10 = ${JSON.stringify(lines)};\n`;
  writeFileSync('src/geo/rivers_10m.js', src);
  console.log(`src/geo/rivers_10m.js  ${(src.length / 1024).toFixed(0)} KB, ${lines.length} rivers`);
}
if (arg('admin1')) {
  const fc0 = JSON.parse(readFileSync(arg('admin1'), 'utf8')), list = arg('countries') || 'THA,LAO,KHM,MYS,MMR,VNM';
  const want = new Set(list === 'all' ? fc0.features.map(f => f.properties.adm0_a3) : list.split(','));
  const dp = (pts, eps) => {   // Douglas-Peucker on a ring (keeps the first and last point)
    if (pts.length < 4) return pts;
    const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1; const st = [[0, pts.length - 1]];
    while (st.length) { const [a, b] = st.pop(); let m = -1, md = eps;
      const [ax, ay] = pts[a], [bx, by] = pts[b], L = Math.hypot(bx - ax, by - ay) || 1e-12;
      for (let i = a + 1; i < b; i++) { const d = Math.abs((bx - ax) * (ay - pts[i][1]) - (ax - pts[i][0]) * (by - ay)) / L; if (d > md) { md = d; m = i; } }
      if (m > 0) { keep[m] = 1; st.push([a, m], [m, b]); } }
    return pts.filter((_, i) => keep[i]);
  };
  // a closed ring starts and ends on the same point (every distance to that 'line' is 0): simplify its two halves
  const tol = +(arg('tolerance') || .01);   // degrees; the whole world at .03 stays a few MB
  const ring = r => { const m = r.length >> 1, s = round([...dp(r.slice(0, m + 1), tol).slice(0, -1), ...dp(r.slice(m), tol)]); return s.length >= 4 ? s : null; };
  const simp = g => g.type === 'Polygon' ? { type: 'Polygon', coordinates: g.coordinates.map(ring).filter(Boolean) }
    : { type: 'MultiPolygon', coordinates: g.coordinates.map(p => p.map(ring).filter(Boolean)).filter(p => p.length) };
  const fc = fc0, out = {};
  for (const f of fc.features) { const p = f.properties; if (!want.has(p.adm0_a3) || !f.geometry) continue; out[`${p.adm0_a3}/${p.name}`] = simp(f.geometry); }
  const src = `// GENERATED by tools/geo_build.mjs --admin1 from Natural Earth 1:10m admin-1 states/provinces (public domain). MODERN borders.\n` +
    `// Countries: ${list === 'all' ? 'all' : [...want].join(', ')} (tolerance ${tol}°). Keys "<ISO3>/<name>". Do not edit: rebuild with more --countries when a story needs them.\n` +
    `(window.GEO = window.GEO || {}).admin1 = ${JSON.stringify(out)};\n`;
  writeFileSync('src/geo/admin1_10m.js', src);
  console.log(`src/geo/admin1_10m.js  ${(src.length / 1024).toFixed(0)} KB, ${Object.keys(out).length} provinces / states`);
}
